import "server-only";
import Database from "better-sqlite3";
import { drizzle } from "drizzle-orm/better-sqlite3";
import { migrate } from "drizzle-orm/better-sqlite3/migrator";
import * as schema from "./schema";
import { getDbPath, getMigrationsDir } from "./paths";

let _db: ReturnType<typeof drizzle<typeof schema>> | null = null;
let _sqlite: Database.Database | null = null;

function init() {
  if (_db) return;
  const sqlite = new Database(getDbPath());
  sqlite.pragma("journal_mode = WAL");
  sqlite.pragma("foreign_keys = ON");
  _sqlite = sqlite;
  _db = drizzle(sqlite, { schema });

  // Auto-run migrations on first access. The migrations folder is generated by
  // `pnpm db:generate` and shipped alongside the app.
  try {
    migrate(_db, { migrationsFolder: getMigrationsDir() });
  } catch (err) {
    console.warn("[db] migrations skipped:", (err as Error).message);
  }
}

export function getDb() {
  init();
  return _db!;
}

export function getSqlite() {
  init();
  return _sqlite!;
}
